/** Reproducible, reviewed host closure. Built at development time, never startup. */
import { build, version as esbuildVersion } from 'esbuild';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = 'server/runtime/gravity-orchard-dependencies.mjs';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/runtime-dependencies-entry.mjs'],
  outfile: output,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // ws optional native accelerators are not a startup or packaging dependency.
  external: ['bufferutil', 'utf-8-validate'],
  write: false,
  metafile: true,
  legalComments: 'inline',
  banner: { js: '// Generated by scripts/bundle-runtime.mjs from reviewed GO2/GO6 sources and locked dependencies.\nimport { createRequire as __sofaCreateRequire } from "node:module";\nconst require = __sofaCreateRequire(import.meta.url);' },
});
const bytes = result.outputFiles[0].contents;
const inputs = [];
const packages = new Map();
const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'));
for (const source of Object.keys(result.metafile.inputs).sort()) {
  if (source.startsWith('<')) continue;
  const data = await readFile(path.join(root, source));
  inputs.push({ path: source, bytes: data.length, sha256: sha256(data) });
  if (!source.includes('node_modules/')) continue;
  const prefix = source.slice(0, source.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const suffix = source.slice(prefix.length).split('/');
  const packageRoot = prefix + suffix.slice(0, suffix[0].startsWith('@') ? 2 : 1).join('/');
  if (packages.has(packageRoot)) continue;
  const metadata = JSON.parse(await readFile(path.join(root, packageRoot, 'package.json'), 'utf8'));
  const licenses = (await readdir(path.join(root, packageRoot))).filter(name => /^(?:licen[cs]e|copyright|notice)(?:[.-]|$)/i.test(name)).sort();
  if (!licenses.length) throw new Error(`Missing bundled dependency license: ${metadata.name}`);
  const texts = [];
  for (const license of licenses) texts.push(await readFile(path.join(root, packageRoot, license), 'utf8'));
  packages.set(packageRoot, { name: metadata.name, version: metadata.version, license: metadata.license,
    integrity: lock.packages[packageRoot]?.integrity, texts });
}
const dependencies = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name, 'en'));
const notices = dependencies.map(item => `${item.name}@${item.version} (${item.license})\n${item.texts.join('\n')}`).join('\n\n');
const manifest = {
  schemaVersion: 1,
  builder: `esbuild@${esbuildVersion}`,
  output: { path: output, bytes: bytes.length, sha256: sha256(bytes) },
  optionalUnbundledAccelerators: ['bufferutil', 'utf-8-validate'],
  requiredExternalRuntimeModules: ['Node.js built-ins only'],
  dependencies: dependencies.map(({ texts, ...item }) => item),
  inputs,
};
const generated = [
  [output, bytes],
  ['server/runtime/dependency-inventory.json', JSON.stringify(manifest, null, 2) + '\n'],
  ['server/runtime/THIRD-PARTY-LICENSES.txt', notices + '\n'],
];
for (const [filename, data] of generated) {
  const target = path.join(root, filename);
  if (process.argv.includes('--check')) {
    const actual = await readFile(target);
    if (!actual.equals(Buffer.from(data))) throw new Error(`Runtime bundle is stale: ${filename}`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, data);
  }
}
console.log(JSON.stringify({ checked: process.argv.includes('--check'), ...manifest.output, dependencies: dependencies.length }));
