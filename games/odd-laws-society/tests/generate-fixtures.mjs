#!/usr/bin/env node
/** Deterministically regenerate safe public examples; --check never writes. */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { projectedFixtures } from './fixture-source.mjs';

const directory = fileURLToPath(new URL('../fixtures/projected/', import.meta.url));

export function expectedFixtureFiles() {
  const fixtures = projectedFixtures();
  const files = Object.fromEntries(Object.entries(fixtures).map(([name, value]) => [`${name}.json`, `${JSON.stringify(value, null, 2)}\n`]));
  files['index.mjs'] = `// Generated by tests/generate-fixtures.mjs. Contains only synthetic role projections.\n`
    + `// Browser-safe: no imports of the authority, private fixtures, or filesystem.\n`
    + `const freeze = value => {\n`
    + `  if (value && typeof value === 'object') {\n`
    + `    for (const child of Object.values(value)) freeze(child);\n`
    + `    Object.freeze(value);\n`
    + `  }\n`
    + `  return value;\n`
    + `};\n\n`
    + `export const PROJECTED_FIXTURES = freeze(${JSON.stringify(fixtures, null, 2)});\n\n`
    + `export const FIXTURE_NAMES = Object.freeze(Object.keys(PROJECTED_FIXTURES));\n\n`
    + `/** Return a fresh mutable snapshot for a fixture harness's selected role. */\n`
    + `export function getProjectedFixture(name, role = 'tv') {\n`
    + `  if (!Object.hasOwn(PROJECTED_FIXTURES, name) || !['tv', 'jon', 'lydia'].includes(role)) {\n`
    + `    throw new RangeError('Choose a known fixture and viewer.');\n`
    + `  }\n`
    + `  return JSON.parse(JSON.stringify(PROJECTED_FIXTURES[name][role]));\n`
    + `}\n`;
  return files;
}

export function generateFixtures({ check = false } = {}) {
  const files = expectedFixtureFiles();
  const expectedNames = Object.keys(files).sort();
  if (check) {
    let actualNames = [];
    try { actualNames = readdirSync(directory).filter(name => /\.(?:json|mjs)$/.test(name)).sort(); } catch { /* Report missing outputs below. */ }
    if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) throw new Error('Projected fixture file list has drifted.');
    for (const name of expectedNames) {
      if (readFileSync(join(directory, name), 'utf8') !== files[name]) throw new Error(`Projected fixture needs regeneration: ${name}`);
    }
  } else {
    mkdirSync(directory, { recursive: true });
    for (const name of expectedNames) writeFileSync(join(directory, name), files[name]);
  }
  return { scenarios: expectedNames.length - 1, files: expectedNames.length, check };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: node games/odd-laws-society/tests/generate-fixtures.mjs [--check]');
  const result = generateFixtures({ check: args[0] === '--check' });
  process.stdout.write(`${result.check ? 'Verified' : 'Generated'} ${result.scenarios} projected scenarios (${result.files} files).\n`);
}
