import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createRun, applyCommand, step, project, serializeCheckpoint, restoreCheckpoint } from '../engine.mjs';
import { RULES, SAFE_INPUT } from '../catalog.mjs';
import { assertPublicView } from '../public.mjs';

const input = { jon: SAFE_INPUT, lydia: SAFE_INPUT };
const actors = {
  host: { role: 'host', playerId: null },
  jon: { role: 'player', playerId: 'jon' },
  lydia: { role: 'player', playerId: 'lydia' },
  public: { role: 'public', playerId: null },
};
const projected = {};
function command(state, actor, kind, payload) {
  const result = applyCommand(state, actor, { kind, payload });
  if (!result.accepted) throw new Error(`Fixture command ${kind} rejected: ${result.code}`);
  return result.state;
}
function bothReady(state) {
  return command(command(state, actors.jon, 'ready', { value: true }), actors.lydia, 'ready', { value: true });
}
function advance(state, ticks) {
  for (let i = 0; i < ticks; i++) state = step(state, input);
  return state;
}
function until(state, predicate, maxTicks = 6000) {
  for (let i = 0; i <= maxTicks; i++) {
    if (predicate(project(state, actors.public))) return state;
    state = step(state, input);
  }
  throw new Error('Fixture did not reach the requested authoritative state.');
}
function capture(name, state) {
  const view = assertPublicView(project(state, actors.host));
  for (const actor of Object.values(actors)) {
    if (JSON.stringify(project(state, actor)) !== JSON.stringify(view)) throw new Error('Cooperative viewer projections unexpectedly differ.');
  }
  projected[name] = view;
}

let state = createRun({ seed: 'go1-public-fixtures-v1', matchId: 'go1-public-fixtures-v1', options: { mode: 'campaign' } });
capture('waiting', state);
state = bothReady(state);
capture('countdown', state);
state = advance(state, RULES.countdownTicks);
state = advance(state, RULES.spawnIntervalTicks * 3);
capture('playing-both-trays', state);
capture('paused', command(state, actors.jon, 'pause', { reason: 'help' }));
capture('restored-paused', restoreCheckpoint(serializeCheckpoint(state)));
state = until(state, view => view.phase === 'interlude');
capture('interlude', state);
state = advance(bothReady(state), RULES.countdownTicks);
state = until(state, view => view.gateStates.some(gate => gate.state === 'forecast'));
capture('gate-forecast', state);
state = until(state, view => view.gateStates.some(gate => gate.state === 'closed'));
capture('gate-closed', state);
state = until(state, view => view.phase === 'interlude');
state = advance(bothReady(state), RULES.countdownTicks);
state = until(state, view => view.gust?.phase === 'forecast');
capture('gust-forecast', state);
state = until(state, view => view.gust?.phase === 'active');
capture('gust-active', state);
state = until(state, view => view.phase === 'finished');
capture('finished', state);
capture('retry-waiting', command(state, actors.host, 'retry-stage', {}));
const practice = advance(bothReady(createRun({ seed: 'go1-public-practice-v1', matchId: 'go1-public-practice-v1', options: { mode: 'practice' } })), RULES.countdownTicks + 840);
capture('practice', practice);

const output = new URL('../fixtures/projected/', import.meta.url);
await mkdir(output, { recursive: true });
const check = process.argv.includes('--check');
const files = Object.entries(projected).map(([name, view]) => [`${name}.json`, `${JSON.stringify(view, null, 2)}\n`]);
files.push(['index.mjs', `// Generated by tests/generate-fixtures.mjs from real engine transitions.\n// Diagnostic fixtures: exclude this module from production browser inventories.\nimport { deepFreeze } from '../../catalog.mjs';\n\nexport const PROJECTED_FIXTURES = deepFreeze(${JSON.stringify(projected, null, 2)});\nexport const FIXTURE_NAMES = Object.freeze(Object.keys(PROJECTED_FIXTURES));\n\nexport function getProjectedFixture(name, viewer = 'public') {\n  if (!Object.hasOwn(PROJECTED_FIXTURES, name) || !['public', 'host', 'tv', 'jon', 'lydia'].includes(viewer)) throw new RangeError('Unknown Gravity Orchard fixture/viewer.');\n  return JSON.parse(JSON.stringify(PROJECTED_FIXTURES[name]));\n}\n`]);
for (const [name, contents] of files) {
  const path = new URL(name, output);
  if (check) {
    let existing;
    try { existing = await readFile(path, 'utf8'); } catch { throw new Error(`Missing generated fixture: ${fileURLToPath(path)}`); }
    if (existing !== contents) throw new Error(`Stale generated fixture: ${fileURLToPath(path)}; run node games/gravity-orchard/tests/generate-fixtures.mjs`);
  } else await writeFile(path, contents);
}
process.stdout.write(`${check ? 'Verified' : 'Generated'} ${Object.keys(projected).length} engine-projected Gravity Orchard fixtures (${files.length} files).\n`);
